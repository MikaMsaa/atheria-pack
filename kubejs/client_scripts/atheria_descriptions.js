NativeEvents.onEvent('net.neoforged.neoforge.event.entity.player.ItemTooltipEvent', event => {
  try {
    var stack = event.getItemStack()
    if (stack.isEmpty()) return
    var id = '' + stack.getItem().builtInRegistryHolder().key().location()
    if (id === 'tacz:ammo') {
      var cd = stack.get(Java.loadClass('net.minecraft.core.component.DataComponents').CUSTOM_DATA)
      if (cd == null) return
      var a = '' + cd.copyTag().getString('AmmoId')
      id = 'tacz:ammo/' + (a.indexOf(':') >= 0 ? a.split(':')[1] : a)
    }
    var t = ATHERIA_DESCRIPTIONS[id]
    if (t) event.getToolTip().add(1, Text.gray(t))
  } catch (e) {}
})
